/* Глава 9. Насколько глубоко можно уйти в рекурсию.
 *
 * Считаем 1 + 2 + ... + 1000000 рекурсией и по дороге печатаем
 * достигнутую глубину. Программа НАРОЧНО написана так, чтобы упасть.
 *
 * Собирать надо БЕЗ оптимизации, иначе компилятор сам превратит эту
 * рекурсию в цикл, и падения не будет:
 *
 *   cc -std=c11 -Wall -Wextra -O0 09-depth.c -o 09-depth
 *   ./09-depth
 *
 * Потом обязательно сравни:
 *
 *   cc -std=c11 -Wall -Wextra -O2 09-depth.c -o 09-depth-fast
 *   ./09-depth-fast
 */

#include <stdio.h>

long depth = 0;                 /* текущая глубина вложенности */

long long sum_to(int n)
{
    depth++;                    /* легла ещё одна «тарелка» на стек */
    if (depth % 10000 == 0) {
        printf("глубина %ld\n", depth);
        fflush(stdout);         /* печатаем сразу, а не в буфер:
                                   после падения буфер пропадёт */
    }
    if (n == 0) {               /* база */
        return 0;
    }
    return n + sum_to(n - 1);   /* шаг */
}

int main(void)
{
    printf("считаем 1+2+...+1000000 рекурсией\n");
    fflush(stdout);
    printf("сумма = %lld\n", sum_to(1000000));
    return 0;
}
